def match_topic_articles(query: str) -> list[tuple[str, str]]:
    """쿼리에 매칭되는 (법령명, 조번호) 목록. 없으면 []."""
    q = resolve_query_aliases(query)
    out: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()
    for keys, pairs in TOPIC_ARTICLES:
        if not any(k in q for k in keys):
            continue
        for pair in pairs:
            if pair not in seen:
                seen.add(pair)
                out.append(pair)
    return out


def expand_alias(text: str) -> str:
    """문장 속 약칭을 정식 법령명으로 치환."""
    out = text
    for alias, full in _ALIAS_MAP:
        if alias in out:
            out = out.replace(alias, full)
    return out


def resolve_query_aliases(query: str) -> str:
    """검색 쿼리용 약칭 확장."""
    return expand_alias(query.strip())


def match_core_law_name(name: str) -> str | None:
    """입력 법령명이 핵심 법령과 일치하면 정식명 반환."""
    n = name.strip().replace("·", "ㆍ").replace("‧", "ㆍ")
    if n in CORE_LAWS:
        return n
    for alias, full in _ALIAS_MAP:
        if n == alias or n == full:
            return full
    for full in CORE_LAWS:
        if full in n or n in full:
            return full
    return None


