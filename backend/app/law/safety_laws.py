def demo_search(query: str) -> list[dict]:
    """데모: 쿼리 키워드로 CORE 법령 필터."""
    q = resolve_query_aliases(query).lower()
    hits = []
    for name in CORE_LAWS:
        if any(tok in name.lower() or tok in q for tok in re.split(r"\s+", q) if len(tok) >= 2):
            hits.append({"law_name": name, "mst": f"demo-{name}", "status": "demo"})
        elif name in q or any(a in query for a in CORE_LAWS[name]["aliases"]):
            hits.append({"law_name": name, "mst": f"demo-{name}", "status": "demo"})
    if not hits:
        # 기본: 산안법 + 중처법
        hits = [
            {"law_name": "산업안전보건법", "mst": "demo-산업안전보건법", "status": "demo"},
            {
                "law_name": "중대재해 처벌 등에 관한 법률",
                "mst": "demo-중대재해 처벌 등에 관한 법률",
                "status": "demo",
            },
        ]
    return hits


def demo_get_article(law_name: str, article_no: str) -> dict | None:
    key_law = match_core_law_name(law_name) or law_name
    art = str(int(article_no)) if article_no.isdigit() else article_no
    return DEMO_ARTICLES.get((key_law, art))
